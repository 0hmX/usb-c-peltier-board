const parseValue = (value: string | number, kind: 'r' | 'c') => {
 if(typeof value === 'number')return value
 const text=value.trim().replace(/Ω|ohms?/gi,'').replace(/[µμ]/g,'u').replace(/F$/i,'')
 const match=text.match(/^([+-]?(?:\d+(?:\.\d*)?|\.\d+))\s*([pnumkKM]?)$/)
 if(!match)throw new Error('Unsupported catalog value '+value)
 const scale:Record<string,number>={p:1e-12,n:1e-9,u:1e-6,m:1e-3,k:1e3,K:1e3,M:1e6,'':1}
 return Number(match[1])*scale[match[2]]
}
